"""供需市场要的持久化与外部能力（SDD 0018 第十一节）。

实现在 app/infrastructure/repositories/market.py 与
app/infrastructure/external/knowbase_user_data.py。
仓库回的都是字典（字段同表）。
"""

from __future__ import annotations

import uuid
from collections.abc import Sequence
from contextlib import AbstractAsyncContextManager
from datetime import date, datetime
from typing import Any, Protocol

Row = dict[str, Any]


class MarketRepository(Protocol):
    def transaction(self) -> AbstractAsyncContextManager[None]: ...

    # 发布主体与资质
    async def publisher_of(self, subject: str) -> Row | None: ...
    async def get_publisher(self, publisher_id: str) -> Row | None: ...
    async def publisher_with_id_hash(
        self, id_hash: str, *, other_than: str
    ) -> bool: ...
    async def save_publisher(self, subject: str, fields: Row) -> Row: ...
    async def review_publisher(self, publisher_id: str, **fields: Any) -> None: ...
    async def approved_publishers(self) -> list[Row]: ...
    async def pending_publishers(self) -> list[Row]: ...
    async def add_document(self, fields: Row) -> Row: ...
    async def documents_of(self, publisher_id: str) -> list[Row]: ...
    async def get_document(self, document_id: str) -> Row | None: ...
    async def keep_documents_until(
        self, document_ids: Sequence[uuid.UUID], until: datetime
    ) -> None: ...
    async def purge_documents(self, now: datetime) -> int: ...
    async def add_license(self, fields: Row) -> Row: ...
    async def licenses_of(self, publisher_id: str) -> list[Row]: ...
    async def get_license(self, license_id: str) -> Row | None: ...
    async def review_license(self, license_id: str, **fields: Any) -> None: ...
    async def pending_licenses(self) -> list[Row]: ...
    async def has_valid_license(
        self, publisher_id: uuid.UUID, category: str, today: date
    ) -> bool: ...
    async def licenses_expiring(self, until: date) -> list[Row]: ...
    async def licenses_expired(self, today: date) -> list[Row]: ...
    async def valid_license_categories(
        self, publisher_id: uuid.UUID, today: date
    ) -> list[str]: ...
    async def add_publisher_change(self, fields: Row) -> None: ...
    async def publisher_changes(self, publisher_id: str) -> list[Row]: ...

    # 小店（SDD 0018 第十一节第 7 之二小节）
    async def nickname_of(self, subject: str) -> str | None: ...
    async def shop_of(self, subject: str) -> Row | None: ...
    async def get_shop(self, shop_id: str) -> Row | None: ...
    async def add_shop(self, subject: str, name: str) -> Row:
        """开店；这个用户已经有店就回那一家（并发也只有一家）。"""
        ...

    async def update_shop(self, shop_id: uuid.UUID, **fields: Any) -> None: ...
    async def add_shop_event(self, fields: Row) -> None: ...
    async def shop_events(self, shop_id: uuid.UUID, limit: int = 50) -> list[Row]: ...
    async def shops_of(self, subjects: Sequence[str]) -> dict[str, Row]: ...
    async def all_shops(
        self, *, q: str | None, status: str | None, limit: int, offset: int
    ) -> list[Row]: ...
    async def shop_supply(
        self, *, public_market: bool, today: date, owner: str | None = None
    ) -> list[Row]:
        """别人看得到的供给与公开需求，一行一样：owner、kind（expert / knowledge /
        demand）、category（需求为空）、updated_at。不管店停没停，由服务层筛。"""
        ...

    async def public_experts(self, owner: str, today: date) -> list[Row]:
        """这个人别人看得到的专家，各带最新一版能请的版本号（version，可能为空）。"""
        ...

    async def reviews_of_seller(self, subject: str, limit: int) -> list[Row]: ...

    # 专家条目
    async def get_knowbot(self, knowbot_id: str) -> Row | None: ...
    async def knowbots_of(self, subject: str) -> list[Row]: ...
    async def update_knowbot(self, knowbot_id: uuid.UUID, **fields: Any) -> None: ...
    async def pending_experts(self) -> list[Row]: ...
    async def public_experts_of(
        self, publisher_id: uuid.UUID, category: str | None
    ) -> list[Row]: ...

    # 知识条目
    async def add_listing(self, fields: Row) -> Row: ...
    async def get_listing(self, listing_id: str) -> Row | None: ...
    async def update_listing(self, listing_id: uuid.UUID, **fields: Any) -> None: ...
    async def listings_of(self, subject: str) -> list[Row]: ...
    async def listed_knowledge(
        self,
        *,
        q: str | None,
        category: str | None,
        limit: int,
        offset: int,
        today: date,
        seller: str | None = None,
    ) -> tuple[list[Row], int]:
        """上架了、卖家现在仍有资格的知识条目（一页，与总数）。"""
        ...

    async def pending_listings(self) -> list[Row]: ...
    async def listings_up(self) -> list[Row]:
        """全部待审、在架的知识条目（后台核资料还在不在）。"""
        ...

    async def listed_by_publisher(
        self, publisher_id: uuid.UUID, category: str | None
    ) -> list[Row]: ...

    # 需求与响应
    async def add_demand(self, fields: Row) -> Row: ...
    async def get_demand(self, demand_id: str) -> Row | None: ...
    async def update_demand(self, demand_id: uuid.UUID, **fields: Any) -> None: ...
    async def demands_of(self, subject: str) -> list[Row]: ...
    async def open_demands(
        self, *, kind: str | None, q: str | None, today: date, limit: int, offset: int
    ) -> tuple[list[Row], int]: ...
    async def add_response(self, fields: Row) -> Row: ...
    async def get_response(self, response_id: str) -> Row | None: ...
    async def responses_to(self, demand_id: uuid.UUID) -> list[Row]: ...
    async def responses_of(self, subject: str) -> list[Row]: ...
    async def update_response(self, response_id: uuid.UUID, **fields: Any) -> None: ...
    async def close_other_responses(
        self, demand_id: uuid.UUID, chosen: uuid.UUID
    ) -> None: ...

    # 交易与评价
    async def add_trade(self, fields: Row) -> Row: ...
    async def start_trade(self, fields: Row) -> Row: ...
    async def trade_by_request(self, buyer: str, request_key: str) -> Row | None: ...
    async def add_request_alias(
        self, buyer: str, request_key: str, trade_id: uuid.UUID
    ) -> None: ...
    async def granting_trade(self, buyer: str, request_digest: str) -> Row | None: ...
    async def update_trade(self, trade_id: uuid.UUID, **fields: Any) -> None: ...
    async def get_trade(
        self, trade_id: str | uuid.UUID, *, for_update: bool = False
    ) -> Row | None: ...
    async def trades(
        self,
        *,
        buyer: str | None = None,
        seller: str | None = None,
        limit: int = 200,
        offset: int = 0,
        granting: bool = False,
    ) -> list[Row]:
        """成交记录；granting 时连还没办完的也列（运营对账用）。"""
        ...

    async def bought_without_resale(self, buyer: str) -> set[str]: ...
    async def add_review(self, fields: Row) -> Row: ...
    async def get_review(self, trade_id: uuid.UUID) -> Row | None: ...
    async def update_review(self, trade_id: uuid.UUID, **fields: Any) -> None: ...
    async def reviews_for(self, listing_prefix: str) -> list[Row]: ...

    # 留言
    async def add_message(self, fields: Row) -> Row: ...
    async def messages(self, thread_kind: str, thread_id: uuid.UUID) -> list[Row]: ...
    async def get_message(self, message_id: str) -> Row | None: ...
    async def hide_message(self, message_id: uuid.UUID) -> None: ...

    # 驻场规则、举报
    async def current_rules(self) -> Row | None: ...
    async def add_rules(self, body: str, created_by: str) -> Row: ...
    async def add_report(self, fields: Row) -> Row: ...
    async def get_report(self, report_id: str) -> Row | None: ...
    async def reports(self, status: str | None) -> list[Row]: ...
    async def update_report(self, report_id: uuid.UUID, **fields: Any) -> None: ...


class KnowledgeVault(Protocol):
    """knowbase 资料库里的知识（契约 user-data/v2，SDD 0043 第 4.3 节）。

    materials：卖家本人凭令牌列他交给 knowmart 的资料（knowbase 的 knowmart 栏，每份
    带 material_id、名字、当前那一版的摘要、许可、能不能卖）；offer_states：后台没有
    本人令牌，以服务身份成批核条目里的资料还在不在、还卖不卖；purchase：成交后请
    knowbase 给买家建使用权，只到成交那一版、不复制（服务身份 user-data-purchase，按
    transaction_ref 幂等）。
    """

    async def materials(self, user_token: str) -> list[Row]: ...

    async def offer_states(
        self, items: Sequence[tuple[str, str]]
    ) -> dict[tuple[str, str], str]:
        """后台以服务身份核（卖家, 资料）还交给着 knowmart、还能卖：offered /
        not_for_sale / gone。没回的不算数。"""
        ...

    async def purchase(
        self,
        *,
        seller: str,
        material_id: str,
        buyer: str,
        transaction_ref: str,
        resale_allowed: bool = False,
    ) -> Row: ...
